// AJAX is not a Programming language
// AJAX stands for Asynchronous JavaScript and XML. It is a technique used in web development to create asynchronous web applications. With AJAX, web applications can send and retrieve data from a server asynchronously (in the background) without interfering with the display and behavior of the existing page.
// AJAX just uses a combination of XMLHttpRequest object, JavaScript, and HTML DOM to exchange data with a web server behind the scenes. This means that it is possible to update parts of a web page, without reloading the whole page.
// Examples of AJAX applications include Google Maps, Gmail, and Facebook, where users can interact with the application without experiencing full page reloads.

